import Phaser from "phaser";

/**
 * BootScene — preloads all placeholder assets then hands off to OverworldScene.
 *
 * Asset paths reference files created by Task 4 (placeholder tilemap).
 * The game will show a black screen until those assets exist on disk.
 */
export class BootScene extends Phaser.Scene {
  constructor() {
    super({ key: "BootScene" });
  }

  preload(): void {
    // Composite ground tileset — bottom layer for layerType-0 metatiles,
    // both layers for layerType-1 metatiles. The latter (flowers, etc.)
    // need their top layer in the ground so the player covers them.
    // Layer-type-0 top layers (trees, signs, fences) are in the foreground.
    this.load.image("mauville_bottom", "/game/tilesets/mauville_ground.png");

    // Top-layer-only tileset used by obstructive overlay sprites
    // (signs etc.) so they only draw the object pixels, not grass bg.
    this.load.image("mauville_top", "/game/tilesets/mauville_top.png");

    // Foreground: single pre-rendered PNG of the top layer (renders above player)
    this.load.image("mauville_foreground", "/game/maps/mauville_foreground.png");

    // Tiled JSON map (generated by scripts/compose-metatiles.mjs)
    this.load.tilemapTiledJSON("mauville", "/game/maps/mauville.json");

    // Brendan spritesheet — original pret format: 144x32, 9 frames of 16x32
    // Frames: 0-2 = down, 3-5 = up, 6-8 = left. Right = flipped left.
    this.load.spritesheet("player", "/game/sprites/emerald/brendan.png", {
      frameWidth: 16,
      frameHeight: 32,
    });

    // NPC spritesheets — same 144x32 9-frame format as Brendan.
    // NOTE: DO NOT add sprites with a different frame layout (like
    // little_boy which is 144x16, or old_man which is 48x32). Adding
    // them here with the wrong dimensions causes them to render as
    // a wide strip showing all 9 frames side-by-side — which looks
    // like a row of duplicate NPCs in the scene.
    const npcSprites = [
      "boy_3",
      "rich_boy",
      "maniac",
      "woman_4",
      "school_kid_m",
      "fat_man",
      // Route NPCs (added when routes were stitched in)
      "woman_1",
      "woman_2",
      "lass",
      "girl_2",
      "girl_3",
      "fisherman",
      "youngster",
      "man_1",
      "pokefan_f",
    ];
    for (const name of npcSprites) {
      this.load.spritesheet(name, `/game/sprites/emerald/${name}.png`, {
        frameWidth: 16,
        frameHeight: 32,
      });
    }

    // Item ball — single 16x16 image (loaded as spritesheet for Grid Engine compat)
    this.load.spritesheet("item_ball", "/game/sprites/emerald/item_ball.png", {
      frameWidth: 16,
      frameHeight: 16,
    });

    // Snorlax blocker — 32x32 single frame (static, doesn't animate).
    // Sourced from pokeemerald's big_snorlax_doll.png. It occupies 2x2
    // tile visual footprint but only sits on 1 grid tile (collision).
    this.load.spritesheet("snorlax", "/game/sprites/emerald/snorlax.png", {
      frameWidth: 32,
      frameHeight: 32,
    });

    // Old Man (day care guy) — 48x32 = 3 frames of 16x32.
    // Loaded as 3-frame spritesheet to match the actual file size.
    // Used as a non-animated NPC (Grid Engine won't use walk animation
    // since the mapping expects 9 frames).
    this.load.spritesheet("old_man", "/game/sprites/emerald/old_man.png", {
      frameWidth: 16,
      frameHeight: 32,
    });
  }

  create(): void {
    this.scene.start("OverworldScene");
  }
}
