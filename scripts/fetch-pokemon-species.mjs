#!/usr/bin/env node
/**
 * One-time fetch — pulls all 386 Gen 1-3 pokémon names from PokeAPI and
 * writes a static TS file the editor can import. Sprite URLs are kept as
 * raw GitHub URLs so we don't need to bundle hundreds of PNGs.
 */
import { writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../src/game/data/pokemonSpecies.ts");

async function main() {
  const r = await fetch("https://pokeapi.co/api/v2/pokemon?limit=386&offset=0");
  const data = await r.json();

  const lines = [];
  lines.push("/**");
  lines.push(" * All 386 Gen 1–3 pokémon — generated by scripts/fetch-pokemon-species.mjs.");
  lines.push(" * Sprites pull from PokeAPI's static CDN (no local bundling required).");
  lines.push(" */");
  lines.push("");
  lines.push("export interface PokemonSpecies {");
  lines.push("  dex: number;");
  lines.push("  name: string;");
  lines.push("  slug: string;");
  lines.push("  spriteUrl: string;");
  lines.push("}");
  lines.push("");
  lines.push("export const POKEMON_SPECIES: readonly PokemonSpecies[] = [");

  data.results.forEach((p, i) => {
    const dex = i + 1;
    const slug = p.name;
    const name = slug
      .split("-")
      .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
      .join(" ");
    const sprite = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/" + dex + ".png";
    lines.push("  { dex: " + dex + ", name: " + JSON.stringify(name) + ", slug: " + JSON.stringify(slug) + ", spriteUrl: " + JSON.stringify(sprite) + " },");
  });

  lines.push("] as const;");
  lines.push("");
  lines.push("export function getSpeciesByDex(dex: number): PokemonSpecies | null {");
  lines.push("  return POKEMON_SPECIES[dex - 1] ?? null;");
  lines.push("}");
  lines.push("");
  lines.push("export function findSpeciesByName(query: string): PokemonSpecies[] {");
  lines.push("  const q = query.trim().toLowerCase();");
  lines.push("  if (!q) return [];");
  lines.push("  return POKEMON_SPECIES.filter((p) =>");
  lines.push("    p.name.toLowerCase().includes(q) || p.slug.includes(q),");
  lines.push("  );");
  lines.push("}");
  lines.push("");

  writeFileSync(OUT, lines.join("\n"));
  console.log("Wrote " + data.results.length + " species to " + OUT);
}

main().catch((e) => { console.error(e); process.exit(1); });
